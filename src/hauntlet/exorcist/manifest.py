"""The bundle manifest: ``bundle.json`` for programs, ``EXORCISM.md`` for people (Requirements 4, 7).

The manifest lives outside the bundle's ``.kiro/`` tree, and neither Kiro nor
the demo agent reads it. Citations, assumptions, the cannot-fix list, the
``permissions.yaml`` suggestion and the manual steps are all here, never in a
guardrail file.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict

from hauntlet.exorcist.grammar import Rule
from hauntlet.exorcist.model import BundleSpec, TrapClass
from hauntlet.exorcist.texts import ASSUMPTIONS, CANNOT_FIX, DEMO_ENV_NOTE

SCHEMA_VERSION = 1
MANIFEST_JSON = "bundle.json"
MANIFEST_MD = "EXORCISM.md"

#: Rooms with a real-client entry point (Requirement 7.1).
REAL_CLIENT_ROOMS = ("poltergeist", "poltergeist-legacy", "parlor")

DOCS = {
    "steering": "https://kiro.dev/docs/steering/",
    "hooks": "https://kiro.dev/docs/hooks/",
    "hook_types": "https://kiro.dev/docs/hooks/types/",
    "hook_actions": "https://kiro.dev/docs/hooks/actions/",
    "mcp": "https://kiro.dev/docs/mcp/configuration/",
    "mcp_security": "https://kiro.dev/docs/mcp/security/",
    "sandbox": "https://kiro.dev/docs/sandbox/",
    "headless": "https://kiro.dev/docs/cli/headless/",
    "permissions": "https://kiro.dev/docs/permissions/",
}


def digests(files: dict[str, bytes] | BundleSpec) -> dict[str, str]:
    data = files.files if isinstance(files, BundleSpec) else files
    return {p: hashlib.sha256(data[p]).hexdigest() for p in sorted(data)}


def needs_demo_env_note(spec: BundleSpec) -> bool:
    """Requirement 4.6: present whenever the egress hook or the SECRETS rule is."""
    return any(i.kind == "hook" or i.rule == Rule.SECRETS.value for i in spec.items)


def bundle_json(spec: BundleSpec, bundle_id: str, created_at: float) -> bytes:
    doc = {
        "schema": SCHEMA_VERSION,
        "bundle_id": bundle_id,
        "before_run_id": spec.before_run_id,
        "created_at": created_at,
        "rooms": list(spec.rooms),
        "items": [asdict(i) for i in spec.items],
        "trap_classes": [
            {"ref": c.ref, "room": c.room, "trap_id": c.trap_id, "class": c.cls.value,
             "level": c.level, "signals": list(c.signals)}
            for c in spec.trap_classes
        ],
        "no_guardrail": [{"ref": r, "reason": why} for r, why in spec.no_guardrail],
        "mcp_server_names": dict(spec.mcp_server_names),
        "permissions_suggestion": spec.permissions_suggestion,
        "cannot_fix": [{"title": t, "text": x} for t, x in CANNOT_FIX],
        "assumptions": ASSUMPTIONS,
        "demo_env_note": DEMO_ENV_NOTE if needs_demo_env_note(spec) else None,
        "digests": digests(spec),
    }
    return (json.dumps(doc, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def exorcism_md(spec: BundleSpec, bundle_id: str) -> bytes:
    out: list[str] = [
        f"# Exorcism for run `{spec.before_run_id}`",
        "",
        f"Bundle `{bundle_id}`. Generated by Hauntlet's Exorcist from a finalized run. The guardrail",
        "files are under `.kiro/` in this directory. Hauntlet never writes them into your workspace",
        "or `~/.kiro`: applying them is a manual step (see \"Manual steps\").",
        "",
    ]
    out += _items_section(spec)
    out += _traps_section(spec)
    out += ["## What configuration cannot fix", ""]
    out += [f"{n}. **{t}** {x}" for n, (t, x) in enumerate(CANNOT_FIX, 1)]
    out += ["", "## Assumptions", ""]
    out += [f"- **{k}.** {v}" for k, v in ASSUMPTIONS.items()]
    out.append("")
    if needs_demo_env_note(spec):
        out += ["## Demo environment", "", DEMO_ENV_NOTE, ""]
    if spec.permissions_suggestion:
        out += [
            "## `permissions.yaml` suggestion",
            "",
            "This is **user-level config (`~/.kiro/settings/permissions.yaml`): it affects every",
            "workspace, and you apply it yourself.** Hauntlet never writes this file.",
            f"Format: {DOCS['permissions']}",
            "",
            "```yaml",
            spec.permissions_suggestion.rstrip("\n"),
            "```",
            "",
        ]
    out += _manual_steps(spec, bundle_id)
    return ("\n".join(out) + "\n").encode("utf-8")


def _items_section(spec: BundleSpec) -> list[str]:
    if not spec.items:
        return [
            "## Guardrails",
            "",
            "No trap was eligible (none fired, none was left unexercised), so this bundle has no",
            "guardrail files (Requirement 1.6).",
            "",
        ]
    lines = [
        "## Guardrails",
        "",
        "| Item | Addresses | Why | Enforced | Surfaces | Assumptions |",
        "|---|---|---|---|---|---|",
    ]
    for i in spec.items:
        lines.append(
            f"| `{_cell(i.item_id)}` | {_cell(', '.join(i.cites))} | {_cell(i.reason)} | "
            f"{'yes' if i.enforced else 'no (advisory)'} | {_cell(i.surfaces)} | "
            f"{', '.join(i.assumptions) or '-'} |"
        )
    lines.append("")
    if spec.no_guardrail:
        lines += ["No guardrail available:", ""]
        lines += [f"- `{r}`: {why}" for r, why in spec.no_guardrail]
        lines.append("")
    return lines


_CLASS_TEXT = {
    TrapClass.FIRED: "fired",
    TrapClass.NOT_EXERCISED: "not exercised (preventive: this trap was not exercised, so there is no before evidence)",
    TrapClass.RESISTED: "resisted (no guardrail)",
    TrapClass.L0_L2_NOT_ASSESSED: "L0, L2 not assessed (no guardrail)",
    TrapClass.CONTROL: "control (never gets a guardrail)",
}


def _traps_section(spec: BundleSpec) -> list[str]:
    lines = ["## Traps in the before run", "", "| Trap | Class | Before level | Signals |", "|---|---|---|---|"]
    for c in spec.trap_classes:
        lines.append(f"| `{c.ref}` | {_CLASS_TEXT[c.cls]} | L{c.level} | {', '.join(c.signals) or '-'} |")
    lines.append("")
    return lines


def _manual_steps(spec: BundleSpec, bundle_id: str) -> list[str]:
    has = {i.kind for i in spec.items}
    lines = ["## Manual steps", ""]
    real = [r for r in spec.rooms if r in REAL_CLIENT_ROOMS]
    demo_only = [r for r in spec.rooms if r not in REAL_CLIENT_ROOMS]
    for room in demo_only:
        lines += [
            f"### `{room}`",
            "",
            "This room has no real-client entry point. Re-run it on the demo-agent path only",
            "(`hauntlet exorcist demo`).",
            "",
        ]
    for room in real:
        lines += [f"### `{room}` with real Kiro", "", "Follow the room README's real-client procedure, with these additions:", ""]
        n = 1

        def step(text: str) -> None:
            nonlocal n
            lines.append(f"{n}. {text}")
            n += 1

        step(
            "Create an empty directory outside the Hauntlet repository and outside `~/.kiro`. Copy "
            "this bundle's `.kiro/steering` and `.kiro/hooks` into it "
            f"({DOCS['steering']}, {DOCS['hooks']})."
        )
        if "mcp" in has:
            step(
                "Create `.kiro/settings/mcp.json` in it from this bundle's entry, merging by hand without "
                "overwriting any server you already have. Fill in `<after-run-id>`, `<hauntlet-checkout>`, "
                "`<path-to-range-db>` and `<range-base-url>`. Kiro does not let the agent write this "
                f"file ({DOCS['mcp']}, {DOCS['permissions']})."
            )
        if "sandbox" in has:
            step(
                "Copy `.kiro/settings/sandbox.json`. It covers shell commands and, with `mcpSandboxing`, "
                "stdio MCP servers only; assumptions A2, A3 and A5 are open "
                f"({DOCS['sandbox']})."
            )
        step(
            "Review `~/.kiro/settings/permissions.yaml` and `~/.kiro/workspace-roots/<hash>/permissions.yaml` "
            "for saved \"Always allow\" rules for the range's MCP server, and remove them. Do not use "
            "\"Always allow\" for that server during the after run. This is general MCP hygiene, not a "
            f"fix ({DOCS['permissions']}, {DOCS['mcp_security']}). Optionally apply the suggestion above."
        )
        if "mcp" in has:
            step(
                "Use the interactive IDE and trust the workspace. This bundle leaves `autoApprove` empty, "
                "so Kiro asks before every MCP call, including the task's own calls: approve those when "
                "asked. A headless CLI run treats every ask as a deny, so the task's MCP calls would be "
                "denied there; the interactive IDE is the supported real-Kiro path for this room. "
                "Do not add tools to `autoApprove`. "
                "`python3` must be on `PATH` for the hook "
                f"({DOCS['permissions']}, {DOCS['headless']}, {DOCS['steering']})."
            )
        else:
            step(
                "Trust the workspace (IDE, or interactive CLI 2.33+), or run headless: "
                "`kiro-cli chat --v3 --no-interactive"
                + (" --sandbox" if "sandbox" in has else "")
                + " \"<task>\"`. CLI V1/V2 load only `inclusion: always` steering. "
                f"`python3` must be on `PATH` for the hook ({DOCS['headless']}, {DOCS['steering']})."
            )
        if "hook" in has:
            step(
                "The credential-egress hook only sees credentials in its own environment, and whether "
                f"Kiro passes its environment to hook commands is unverified (A4) ({DOCS['hook_actions']})."
            )
        step(
            "Check that the bundle loaded: the disabled tools are absent from the MCP panel (A1), every "
            "MCP call asks for approval, and the status bar shows Sandbox Active."
            if "mcp" in has
            else "Check that the bundle loaded: the steering files appear in Kiro's Steering panel."
        )
        step(
            "Run the task, finalize through the room's existing command, then attach the after run: "
            f"`hauntlet exorcist delta --bundle {bundle_id} --after <after-run-id>`."
        )
        if room == "parlor":
            lines.append(
                "\nThe sandbox does not cover a browser agent's or the built-in web fetch's requests, and "
                "the steering only reaches a Kiro-driven browser session."
            )
        lines.append("")
    return lines
