"""Render guardrail files to bytes. Deterministic: same inputs, same bytes (Requirement 2.5).

No timestamps, sorted lists, ``\\n`` line ends. Formats follow the verified
Kiro docs (requirements.md, "Kiro formats, verified against current docs").
"""

from __future__ import annotations

import json
from collections.abc import Iterable, Mapping
from importlib.resources import files

from hauntlet.exorcist.catalogue import EGRESS_HOOKS, EGRESS_TIMEOUT_SECS, GUARD_PATH
from hauntlet.exorcist.grammar import Rule, render
from hauntlet.exorcist.model import McpTools, Source

#: Literal placeholders the tester fills in (Requirement 2.3); no URL or host.
AFTER_RUN = "<after-run-id>"
CHECKOUT = "<hauntlet-checkout>"
DB_PATH = "<path-to-range-db>"
BASE_URL = "<range-base-url>"


def _json(obj: object) -> bytes:
    return (json.dumps(obj, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def steering_file(title: str, rules: Iterable[tuple[Rule, frozenset[Source]]]) -> bytes:
    """``inclusion: always`` front matter first, a title, one bullet per rule."""
    lines = ["---", "inclusion: always", "---", f"# {title}", ""]
    lines += [f"- {render(rule, srcs)}" for rule, srcs in rules]
    return ("\n".join(lines) + "\n").encode("utf-8")


def egress_hook_file() -> bytes:
    command = f"python3 {GUARD_PATH}"
    return _json(
        {
            "version": "v1",
            "hooks": [
                {
                    "name": name,
                    "description": (
                        "Block a tool call whose input carries the value of a credential-like "
                        "environment variable (generated by Hauntlet's Exorcist)."
                    ),
                    "trigger": "PreToolUse",
                    "matcher": matcher,
                    "action": {"type": "command", "command": command},
                    "timeout": EGRESS_TIMEOUT_SECS,
                }
                for name, matcher in EGRESS_HOOKS
            ],
        }
    )


def guard_script() -> bytes:
    return files("hauntlet.exorcist.guards").joinpath("credential_egress.py").read_bytes()


def server_name(room: str) -> str:
    """``hauntlet_<room>`` with only ``[a-z0-9_]``, so Kiro's ``mcp_<server>_<tool>`` ID is predictable."""
    return "hauntlet_" + "".join(c if c.isalnum() else "_" for c in room.lower())


def mcp_entry(room: str, tools: McpTools) -> dict:
    return {
        "command": "uv",
        "args": [
            "--directory", CHECKOUT, "run", "hauntlet", "mcp", "serve",
            "--room", room, "--run", AFTER_RUN,
        ],
        "env": {"HAUNTLET_DB": DB_PATH, "HAUNTLET_BASE_URL": BASE_URL},
        # Always empty: a tool's description can change after it was approved,
        # so every call asks (exorcist Requirement 2.3, checkpoint-8 review).
        "autoApprove": [],
        "disabledTools": list(tools.not_needed()),
    }


def mcp_file(entries: Mapping[str, dict]) -> bytes:
    return _json({"mcpServers": {name: entries[name] for name in sorted(entries)}})


def sandbox_file(mcp_sandboxing: bool) -> bytes:
    body: dict[str, object] = {"enabled": True, "networkAccess": "DEFAULT_BLOCKED"}
    if mcp_sandboxing:
        body["mcpSandboxing"] = True
    return _json(body)
