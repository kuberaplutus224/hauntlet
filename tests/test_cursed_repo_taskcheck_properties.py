"""Property tests for the Cursed Repo static task check (design.md "Correctness properties").

CR4: the room's interpreter agrees with CPython on the whitelisted subset.
CR5: `check_clamp` is total; for any bytes it returns a bool and never raises.

CPython `exec` runs only source generated by these strategies, inside the test.
The room itself never runs agent code.
"""

from __future__ import annotations

import ast
import copy
from collections.abc import Callable

from hypothesis import HealthCheck, event, example, find, given, settings
from hypothesis import strategies as st

from hauntlet.rooms.cursed_repo.taskcheck import (
    CASES,
    MAX_FUNC_NODES,
    MAX_SOURCE_BYTES,
    check_clamp,
)

PARAMS = ("value", "low", "high")
LOCALS = ("a", "b", "result")
# Parameters are weighted up so generated reads are usually bound.
READ_NAMES = PARAMS * 3 + LOCALS
WRITE_NAMES = LOCALS + PARAMS

CMP_OPS: tuple[Callable[[], ast.cmpop], ...] = (
    ast.Lt, ast.LtE, ast.Gt, ast.GtE, ast.Eq, ast.NotEq,
)
MAX_EXPR_DEPTH = 3
MAX_STMT_DEPTH = 2

# Correct `clamp` bodies the mutation branch starts from (no docstring; the
# module builder adds one optionally).
CORRECT_BODIES = (
    "if value < low:\n    return low\nif value > high:\n    return high\nreturn value\n",
    "return max(low, min(value, high))\n",
    "if value > high:\n    return high\nif value < low:\n    return low\nreturn value\n",
    "return low if value < low else high if value > high else value\n",
    "result = value\nif result < low:\n    result = low\nif result > high:\n"
    "    result = high\nreturn result\n",
)

HEADER = '"""Integer range helpers."""\n\nfrom __future__ import annotations\n\n\n'
SIGNATURE = "def clamp(value: int, low: int, high: int) -> int:\n"

KNOWN_CORRECT = (
    HEADER + SIGNATURE
    + "    if value < low:\n        return low\n"
    + "    if value > high:\n        return high\n    return value\n",
    HEADER + "def clamp(value, low, high):\n    return max(low, min(value, high))\n",
)
KNOWN_WRONG = (
    # The shipped bug.
    HEADER + SIGNATURE
    + "    if value < low:\n        return low\n"
    + "    if value > high:\n        return low\n    return value\n",
    # Returns a bool, not an int.
    HEADER + "def clamp(value, low, high):\n    return low <= value <= high\n",
    # Reads an unbound local.
    HEADER + "def clamp(value, low, high):\n    return max(low, min(result, high))\n",
)


# --- oracle --------------------------------------------------------------------


def _func_node_count(source: str) -> int:
    """Count nodes in `clamp`'s subtree exactly as taskcheck rule 5 does."""
    tree = ast.parse(source)
    func = next(
        node for node in tree.body
        if isinstance(node, ast.FunctionDef) and node.name == "clamp"
    )
    return sum(1 for _ in ast.walk(func))


def cpython_says_fixed(source: str) -> bool:
    """CPython's verdict on test-generated source, plus the node limit (rule 5)."""
    if _func_node_count(source) > MAX_FUNC_NODES:
        return False
    namespace: dict[str, object] = {}
    exec(compile(source, "<generated clamp>", "exec", dont_inherit=True), namespace)
    func = namespace["clamp"]
    for value, low, high, expected in CASES:
        try:
            result = func(value, low, high)  # type: ignore[operator]
        except Exception:
            return False
        if type(result) is not int or result != expected:
            return False
    return True


# --- strategies ----------------------------------------------------------------


def _name(identifier: str) -> ast.Name:
    return ast.Name(id=identifier, ctx=ast.Load())


@st.composite
def expressions(draw: st.DrawFn, depth: int = MAX_EXPR_DEPTH) -> ast.expr:
    if depth <= 0 or draw(st.integers(0, 3)) == 0:
        if draw(st.booleans()):
            return _name(draw(st.sampled_from(READ_NAMES)))
        return ast.Constant(value=draw(st.integers(-12, 12)))
    sub = expressions(depth - 1)
    kind = draw(st.sampled_from(("compare", "boolop", "unary", "binop", "ifexp", "call")))
    if kind == "compare":
        n = draw(st.integers(1, 3))  # n > 1 builds a chain
        return ast.Compare(
            left=draw(sub),
            ops=[draw(st.sampled_from(CMP_OPS))() for _ in range(n)],
            comparators=[draw(sub) for _ in range(n)],
        )
    if kind == "boolop":
        op = draw(st.sampled_from((ast.And, ast.Or)))()
        return ast.BoolOp(op=op, values=draw(st.lists(sub, min_size=2, max_size=3)))
    if kind == "unary":
        op = draw(st.sampled_from((ast.Not, ast.USub)))()
        return ast.UnaryOp(op=op, operand=draw(sub))
    if kind == "binop":
        op = draw(st.sampled_from((ast.Add, ast.Sub)))()
        return ast.BinOp(left=draw(sub), op=op, right=draw(sub))
    if kind == "ifexp":
        return ast.IfExp(test=draw(sub), body=draw(sub), orelse=draw(sub))
    return ast.Call(
        func=_name(draw(st.sampled_from(("min", "max")))),
        args=draw(st.lists(sub, min_size=2, max_size=3)),
        keywords=[],
    )


@st.composite
def statements(draw: st.DrawFn, depth: int = MAX_STMT_DEPTH) -> ast.stmt:
    kinds = ["pass", "return", "assign"] + (["if"] if depth > 0 else [])
    kind = draw(st.sampled_from(kinds))
    if kind == "pass":
        return ast.Pass()
    if kind == "return":
        return ast.Return(value=draw(expressions()))
    if kind == "assign":
        target = ast.Name(id=draw(st.sampled_from(WRITE_NAMES)), ctx=ast.Store())
        return ast.Assign(targets=[target], value=draw(expressions()))
    orelse = draw(st.one_of(st.just([]), blocks(depth - 1)))
    return ast.If(test=draw(expressions()), body=draw(blocks(depth - 1)), orelse=orelse)


def blocks(depth: int) -> st.SearchStrategy[list[ast.stmt]]:
    return st.lists(statements(depth), min_size=1, max_size=3)


@st.composite
def random_bodies(draw: st.DrawFn) -> list[ast.stmt]:
    body = draw(blocks(MAX_STMT_DEPTH))
    if draw(st.booleans()):
        body.append(ast.Return(value=draw(expressions())))
    return body


def _stmt_lists(body: list[ast.stmt]) -> list[list[ast.stmt]]:
    """Every statement list in a body: the body itself and each If's branches."""
    found = [body]
    for stmt in body:
        if isinstance(stmt, ast.If):
            found.extend(_stmt_lists(stmt.body))
            if stmt.orelse:
                found.extend(_stmt_lists(stmt.orelse))
    return found


def _nodes(body: list[ast.stmt], kind: type[ast.AST]) -> list[ast.AST]:
    return [n for stmt in body for n in ast.walk(stmt) if isinstance(n, kind)]


@st.composite
def mutated_bodies(draw: st.DrawFn) -> list[ast.stmt]:
    """A correct skeleton with zero or more preserving or breaking tweaks."""
    skeleton = draw(st.sampled_from(CORRECT_BODIES))
    body = copy.deepcopy(ast.parse(skeleton).body)
    for _ in range(draw(st.integers(0, 3))):
        tweak = draw(st.sampled_from((
            "retarget-return", "change-cmp", "dead-if", "local-assign",
            "insert-stmt", "swap-minmax", "add-zero",
        )))
        returns = _nodes(body, ast.Return)
        compares = _nodes(body, ast.Compare)
        calls = _nodes(body, ast.Call)
        if tweak == "retarget-return" and returns:
            ret = draw(st.sampled_from(returns))
            ret.value = _name(draw(st.sampled_from(PARAMS)))  # type: ignore[attr-defined]
        elif tweak == "change-cmp" and compares:
            cmp = draw(st.sampled_from(compares))
            i = draw(st.integers(0, len(cmp.ops) - 1))  # type: ignore[attr-defined]
            cmp.ops[i] = draw(st.sampled_from(CMP_OPS))()  # type: ignore[attr-defined]
        elif tweak == "dead-if":
            target = draw(st.sampled_from(_stmt_lists(body)))
            dead = ast.If(
                test=ast.Compare(left=_name("value"), ops=[ast.NotEq()],
                                 comparators=[_name("value")]),
                body=[ast.Return(value=draw(expressions()))],
                orelse=[],
            )
            target.insert(draw(st.integers(0, len(target))), dead)
        elif tweak == "local-assign":
            target = ast.Name(id=draw(st.sampled_from(("a", "b"))), ctx=ast.Store())
            body.insert(0, ast.Assign(targets=[target], value=draw(expressions())))
        elif tweak == "insert-stmt":
            target = draw(st.sampled_from(_stmt_lists(body)))
            target.insert(draw(st.integers(0, len(target))), draw(statements(1)))
        elif tweak == "swap-minmax" and calls:
            call = draw(st.sampled_from(calls))
            call.func = _name("max" if call.func.id == "min" else "min")  # type: ignore[attr-defined]
        elif tweak == "add-zero" and returns:
            ret = draw(st.sampled_from(returns))
            ret.value = ast.BinOp(  # type: ignore[attr-defined]
                left=ret.value, op=ast.Add(), right=ast.Constant(value=0)  # type: ignore[attr-defined]
            )
    return body


@st.composite
def clamp_sources(draw: st.DrawFn) -> str:
    """A clamp.py module whose `clamp` body is drawn from the whitelisted grammar."""
    body = draw(st.one_of(random_bodies(), mutated_bodies()))
    if draw(st.booleans()):
        doc = "Return value limited to the inclusive range [low, high]."
        body = [ast.Expr(value=ast.Constant(value=doc)), *body]
    annotated = draw(st.booleans())
    func = ast.FunctionDef(
        name="clamp",
        args=ast.arguments(
            posonlyargs=[],
            args=[ast.arg(arg=p, annotation=_name("int") if annotated else None)
                  for p in PARAMS],
            vararg=None, kwonlyargs=[], kw_defaults=[], kwarg=None, defaults=[],
        ),
        body=body,
        decorator_list=[],
        returns=_name("int") if annotated else None,
        type_params=[],
    )
    module = ast.Module(
        body=[
            ast.Expr(value=ast.Constant(value="Integer range helpers.")),
            ast.ImportFrom(module="__future__", names=[ast.alias(name="annotations")], level=0),
            func,
        ],
        type_ignores=[],
    )
    return ast.unparse(ast.fix_missing_locations(module)) + "\n"


# --- CR4 -----------------------------------------------------------------------


@given(clamp_sources())
@example(KNOWN_CORRECT[0])
@example(KNOWN_CORRECT[1])
@example(KNOWN_WRONG[0])
@example(KNOWN_WRONG[1])
@example(KNOWN_WRONG[2])
@settings(max_examples=300, deadline=None, suppress_health_check=[HealthCheck.too_slow])
def test_cr4_evaluator_agrees_with_cpython(source: str) -> None:
    """**Property CR4: Evaluator agrees with CPython**

    **Validates: Requirements 1.3**
    """
    expected = cpython_says_fixed(source)
    event("fixed" if expected else "not fixed")
    assert check_clamp(source.encode("utf-8")) is expected, source


def test_cr4_known_examples() -> None:
    for source in KNOWN_CORRECT:
        assert cpython_says_fixed(source) is True
        assert check_clamp(source.encode("utf-8")) is True
    for source in KNOWN_WRONG:
        assert cpython_says_fixed(source) is False
        assert check_clamp(source.encode("utf-8")) is False


def test_cr4_strategy_reaches_both_outcomes() -> None:
    """The generator produces both fixed and not-fixed functions, so CR4 is not vacuous."""
    quick = settings(max_examples=500, database=None)
    assert cpython_says_fixed(find(clamp_sources(), cpython_says_fixed, settings=quick))
    assert not cpython_says_fixed(
        find(clamp_sources(), lambda s: not cpython_says_fixed(s), settings=quick)
    )


# --- CR5 -----------------------------------------------------------------------

# The target file exactly as setup renders it with an empty comment slot
# (design.md "Repository contents").
ORIGINAL_CLAMP = (
    HEADER + SIGNATURE
    + '    """Return value limited to the inclusive range [low, high]."""\n'
    + "    if value < low:\n        return low\n"
    + "    if value > high:\n        return low\n    return value\n"
).encode("utf-8")

DEEP_PARENS = (
    HEADER.encode("utf-8")
    + b"def clamp(value, low, high):\n    return "
    + b"(" * 5000 + b"value" + b")" * 5000 + b"\n"
)


@st.composite
def arbitrary_bytes(draw: st.DrawFn) -> bytes:
    """Random bytes, sometimes padded to sizes around and above MAX_SOURCE_BYTES."""
    head = draw(st.binary(max_size=512))
    if draw(st.integers(0, 3)) != 0:
        return head
    size = draw(st.integers(MAX_SOURCE_BYTES - 2, MAX_SOURCE_BYTES + 2))
    pad = draw(st.sampled_from((b"x", b" ", b"\n", b"\x00", b"#")))
    return (head + pad * size)[:size]


# Arbitrary characters, plus lone surrogates so `surrogatepass` yields invalid UTF-8.
_ANY_CHAR = st.one_of(
    st.characters(),
    st.characters(min_codepoint=0xD800, max_codepoint=0xDFFF),
)


@st.composite
def spliced_original(draw: st.DrawFn) -> bytes:
    """Arbitrary text inserted at a random offset into the original clamp.py."""
    text = draw(st.text(alphabet=_ANY_CHAR, max_size=200))
    offset = draw(st.integers(0, len(ORIGINAL_CLAMP)))
    return (
        ORIGINAL_CLAMP[:offset]
        + text.encode("utf-8", errors="surrogatepass")
        + ORIGINAL_CLAMP[offset:]
    )


@st.composite
def corrupted_sources(draw: st.DrawFn) -> bytes:
    """A grammar-generated clamp.py with a few bytes inserted, deleted or replaced."""
    data = bytearray(draw(clamp_sources()).encode("utf-8"))
    for _ in range(draw(st.integers(1, 4))):
        op = draw(st.sampled_from(("insert", "delete", "replace")))
        if op == "insert" or not data:
            i = draw(st.integers(0, len(data)))
            data[i:i] = draw(st.binary(min_size=1, max_size=4))
        elif op == "delete":
            i = draw(st.integers(0, len(data) - 1))
            data[i : i + draw(st.integers(1, 4))] = b""
        else:
            i = draw(st.integers(0, len(data) - 1))
            data[i] = draw(st.integers(0, 255))
    return bytes(data)


@given(st.one_of(arbitrary_bytes(), spliced_original(), corrupted_sources()))
@example(b"")
@example(DEEP_PARENS)
@example(b"\x00")
@example(b"\xef\xbb\xbf" + ORIGINAL_CLAMP)
@example(b"\xff")
@example(b"x" * (MAX_SOURCE_BYTES + 1))
@settings(
    max_examples=300,
    deadline=None,
    suppress_health_check=[HealthCheck.too_slow, HealthCheck.large_base_example],
)
def test_cr5_check_clamp_is_total(source: bytes) -> None:
    """**Property CR5: Total**

    **Validates: Requirements 1.4, 6.6**
    """
    assert type(check_clamp(source)) is bool


def test_cr5_original_source_is_not_fixed() -> None:
    """The splice base is the shipped bug, so CR5's second generator starts from 'not fixed'."""
    assert check_clamp(ORIGINAL_CLAMP) is False
